// Content schema. Authored JSON lives in src/content and is validated by scripts/build-index.ts.

export type Tier = 1 | 2 | 3 | 4 | 5;
export const TIER_NAMES = ['Novice', 'Apprentice', 'Adept', 'Expert', 'Master'] as const;

export interface Domain {
  id: string;
  name: string;
  color: string; // '#rrggbb', tints the domain's nebula and stars
  blurb: string;
}

export type Social = 'solo' | 'group' | 'either';
export type Setting = 'indoor' | 'outdoor' | 'either';
export type Focus = 'physical' | 'mental' | 'creative';

export interface HobbyStats {
  difficulty: 1 | 2 | 3 | 4 | 5;
  hours: number; // rough hours to basic competence
  cost: 0 | 1 | 2 | 3 | 4; // 0 free · 1 <$50 · 2 <$250 · 3 <$1000 · 4 $1000+
  gear: string[];
  social: Social;
  setting: Setting;
  focus: Focus[];
}

/** One entry in src/content/hobbies/<domainId>.json */
export interface Hobby {
  id: string;
  name: string;
  summary: string;
  pop: 1 | 2 | 3 | 4 | 5; // how widely practised; drives star size and label priority
  stats: HobbyStats;
  tags: string[];
  synergies: string[]; // other hobby ids; ids that don't exist yet are ignored at runtime
  partyTrick?: boolean; // the hobby offers quick, impressive wins
  safety?: string;
}

/** One node in src/content/trees/<hobbyId>.json */
export interface SkillNode {
  id: string;
  name: string;
  tier: Tier;
  requires: string[]; // node ids in the same tree
  summary: string;
  steps: string[];
  drills: string[];
  mastery: string; // "You've got it when..."
  hours: number;
  partyTrick?: number; // minutes to learn, when this node is a quick party trick
}

export interface SkillTree {
  hobby: string;
  nodes: SkillNode[];
}

/** Generated by scripts/build-index.ts into src/content/_meta.json */
export interface HobbyMeta {
  nodes: number;
  tiers: number[]; // node count per tier, index 0 = Novice
  party: { id: string; name: string; minutes: number; tier: Tier }[];
}
export interface ContentMeta {
  generated: string;
  hobbies: Record<string, HobbyMeta>;
}

/** Generated into src/content/_search.json: [hobbyId, nodeId, nodeName, tier] */
export type SearchRow = [string, string, string, Tier];

export type Vec2 = [number, number];

// Runtime shapes, with derived fields added by src/lib/data.ts
export interface DomainEntry extends Domain {
  index: number;
  code: string; // short sector code shown on the map, e.g. "SEC-09"
  pos: Vec2; // centre of the district (world units)
  cells: [number, number][]; // every tile of the district in axial coordinates, hobbies first
  border: number[]; // outline segments, flat [x1, y1, x2, y2, …]
  bounds: { minX: number; minY: number; maxX: number; maxY: number };
  hobbies: number[]; // indices into Galaxy.hobbies
}

export interface HobbyEntry extends Hobby {
  index: number;
  domain: string;
  domainIndex: number;
  cell: [number, number]; // axial coordinates of its tile
  pos: Vec2; // tile centre (world units)
  charted: boolean; // has a full skill tree
  meta: HobbyMeta | null;
}
